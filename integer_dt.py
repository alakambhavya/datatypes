#integer to binary,octal,hex_decimal format
roll=458
print("integer format'roll':",roll)
print("binary  format'roll':",bin(roll))
print("octal  format'roll':",oct(roll))
print("hex_decimal  format'roll':",hex(roll))

print("____________")

#binary to octal,hex_decimal format
dec=0b110001010
print(dec)
print(type(dec))
octal_1=oct(dec)
print(octal_1)
print(type(octal_1))
hex_decimal_1=hex(dec)
print(hex_decimal_1)
print(type(hex_decimal_1))

print("___________")

